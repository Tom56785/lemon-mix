# Regenerates LICENSES/Rust-crates.txt: the licence and notice of every Rust
# crate compiled into LemonMix.exe. Run it after changing dependencies:
#
#     powershell -ExecutionPolicy Bypass -File scripts\update-licenses.ps1
#
# Crates used only while building (procedural macros and their dependencies,
# and build-script dependencies such as the icon writer) are not part of the
# executable and are left out, as are the workspace's own crates and the
# vendored webbrowser stand-in, which are covered by ../LICENSE.

$ErrorActionPreference = 'Stop'
$target = 'x86_64-pc-windows-gnu'
$package = 'lemon-mix'
$root = Split-Path -Parent $PSScriptRoot
$output = Join-Path $root 'LICENSES\Rust-crates.txt'

Push-Location $root
try {
    $metadata = cargo metadata --format-version 1 --filter-platform $target | ConvertFrom-Json
    if ($LASTEXITCODE -ne 0) { throw 'cargo metadata failed' }

    # Runtime dependencies only: normal edges, without procedural macros.
    $tree = cargo tree -p $package -e normal,no-proc-macro --target $target --prefix none --format '{p}'
    if ($LASTEXITCODE -ne 0) { throw 'cargo tree failed' }
    $crates = $tree |
        ForEach-Object { ($_ -replace ' \(\*\)$', '') -replace ' \(.*\)$', '' } |
        Where-Object { $_ -match '^\S+ v\S+$' } |
        Sort-Object -Unique |
        ForEach-Object {
            $name, $version = $_ -split ' v'
            $metadata.packages | Where-Object { $_.name -eq $name -and $_.version -eq $version }
        } |
        # Path crates (no registry source) are this repository's own code.
        Where-Object { $null -ne $_.source } |
        Sort-Object name, version

    # The notice reproduced for each crate. Where a crate offers MIT, its MIT
    # notice is used; otherwise the notice of the licence it offers.
    $mitFiles = 'LICENSE-MIT', 'license-mit', 'LICENSE-MIT.md', 'LICENSE-MIT.txt', 'LICENSE', 'LICENSE.md', 'LICENSE.txt', 'COPYING'
    $apacheFiles = 'LICENSE-APACHE', 'license-apache', 'LICENSE-APACHE.md', 'LICENSE-APACHE.txt', 'LICENSE', 'LICENSE.md', 'LICENSE.txt'
    $otherFiles = 'LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENSE-ZLIB', 'LICENSE-ZLIB.md', 'LICENSE-BSD', 'LICENSE-ISC',
        'LICENSE-UNICODE', 'COPYING', 'COPYRIGHT'
    # Apache-2.0 asks for a crate's NOTICE file to travel with it.
    $extraFiles = 'NOTICE', 'NOTICE.md', 'NOTICE.txt'
    # Crates published without a licence file: their notice, copied from the
    # crate's repository into LICENSES/notices. Add an entry here when the
    # script warns about a new crate.
    $noticeDir = Join-Path $root 'LICENSES\notices'
    $fallbacks = @{
        'clipboard-win' = 'clipboard-win-BSL-1.0.txt'
        'ecolor' = 'egui-MIT.txt'
        'eframe' = 'egui-MIT.txt'
        'egui' = 'egui-MIT.txt'
        'egui_glow' = 'egui-MIT.txt'
        'egui-winit' = 'egui-MIT.txt'
        'emath' = 'egui-MIT.txt'
        'epaint' = 'egui-MIT.txt'
        'epaint_default_fonts' = 'egui-MIT.txt'
        'profiling' = 'profiling-MIT.txt'
        'winapi-x86_64-pc-windows-gnu' = 'winapi-MIT.txt'
    }

    $rule = '-' * 72
    $text = New-Object System.Text.StringBuilder
    $lines = @(
        'Third-party Rust crates compiled into Lemon Mix'
        '==============================================='
        ''
        'LemonMix.exe includes code from the crates below. Each is distributed'
        'under the licence shown; where a crate offers a choice of licences,'
        'Lemon Mix uses it under the MIT licence, whose notice is reproduced'
        'below. Crates used only while building (procedural macros and the icon'
        'writer) are not part of the executable and are not listed. The fonts'
        'built into the window come with epaint_default_fonts; their licences'
        'follow that crate''s entry.'
        ''
        'Generated by scripts/update-licenses.ps1.'
        ''
    )
    foreach ($line in $lines) { [void]$text.Append("$line`n") }

    $missing = @()
    foreach ($crate in $crates) {
        $dir = Split-Path -Parent $crate.manifest_path
        $licence = "$($crate.license)"
        $candidates = if ($licence -match '\bMIT\b') { $mitFiles }
            elseif ($licence -match 'Apache-2\.0') { $apacheFiles }
            else { $otherFiles }
        if ($crate.license_file) { $candidates = @($crate.license_file) + $candidates }
        $notice = $candidates | Where-Object { Test-Path -LiteralPath (Join-Path $dir $_) -PathType Leaf } | Select-Object -First 1
        $noticePath = if ($notice) { Join-Path $dir $notice } else { $null }
        if (-not $notice -and $fallbacks.ContainsKey($crate.name)) {
            $notice = "LICENSES/notices/$($fallbacks[$crate.name]) (from the repository)"
            $noticePath = Join-Path $noticeDir $fallbacks[$crate.name]
        }
        $extras = @($extraFiles | Where-Object { Test-Path -LiteralPath (Join-Path $dir $_) -PathType Leaf })
        $fontDir = Join-Path $dir 'fonts'
        if (Test-Path -LiteralPath $fontDir -PathType Container) {
            $extras += Get-ChildItem -LiteralPath $fontDir -Filter '*.txt' | Sort-Object Name | ForEach-Object { "fonts/$($_.Name)" }
        }
        if (-not $licence) { $licence = "see $($crate.license_file)" }

        $header = @($rule, "$($crate.name) $($crate.version)", "Licence: $licence", "Source:  $($crate.repository)",
            "Notice:  $(@($notice) + $extras -join ', ')", $rule, '')
        foreach ($line in $header) { [void]$text.Append("$line`n") }
        if (-not $notice) {
            [void]$text.Append("(NO LICENCE FILE FOUND - check the crate's repository)`n`n")
            $missing += "$($crate.name) $($crate.version)"
        }
        $paths = @($noticePath) + @($extras | ForEach-Object { Join-Path $dir $_ })
        $labels = @($null) + $extras
        for ($i = 0; $i -lt $paths.Count; $i++) {
            if (-not $paths[$i]) { continue }
            if ($labels[$i]) { [void]$text.Append("--- $($labels[$i]) ---`n`n") }
            $content = [IO.File]::ReadAllText($paths[$i]) -replace "`r", ''
            [void]$text.Append($content.TrimEnd("`n") + "`n`n")
        }
    }

    [IO.File]::WriteAllText($output, $text.ToString(), (New-Object System.Text.UTF8Encoding $false))
    Write-Host "Wrote $output with $(@($crates).Count) crates:"
    $crates | ForEach-Object { Write-Host "  $($_.name) $($_.version)  [$($_.license)]" }
    foreach ($crate in $missing) { Write-Warning "$crate has no licence file" }
} finally {
    Pop-Location
}
